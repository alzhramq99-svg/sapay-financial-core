#!/usr/bin/env bash
set -euo pipefail

app_path="${1:?Usage: verify-ios-app.sh path/to/App.app}"
plist="$app_path/Info.plist"
web_source="../public"

assert_plist_value() {
  local key="$1" expected="$2" actual
  actual="$(/usr/libexec/PlistBuddy -c "Print :$key" "$plist")"
  if [[ "$actual" != "$expected" ]]; then
    printf '%s: expected %s, got %s\n' "$key" "$expected" "$actual" >&2
    return 1
  fi
}

test -d "$app_path"
assert_plist_value CFBundleIdentifier com.saadaligroup.sapay
assert_plist_value CFBundleDisplayName SApay
assert_plist_value UIUserInterfaceStyle Dark
assert_plist_value CFBundleIcons:CFBundlePrimaryIcon:CFBundleIconName AppIcon
test -n "$(/usr/libexec/PlistBuddy -c 'Print :NSFaceIDUsageDescription' "$plist")"
test -s "$app_path/Assets.car"

# Compare every source asset, including the Face ID bridge generated by cap:sync.
while IFS= read -r -d '' source; do
  cmp "$source" "$app_path/public/${source#"$web_source/"}"
done < <(find "$web_source" -type f -print0)

printf 'Verified SApay app bundle at %s\n' "$app_path"
